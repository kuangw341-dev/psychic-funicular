# risk/dynamic_sl.py

class DynamicSL:

    def __init__(self):
        pass

    # ==================================================

    def calculate(self, atr, trend_strength):
        base_sl = atr * 1.5

        # ==================================================
        # 趋势强
        # ==================================================

        if trend_strength > 0.03:
            base_sl *= 1.5

        # ==================================================
        # 趋势弱
        # ==================================================

        elif trend_strength < 0.01:
            base_sl *= 0.7

        # ==================================================

        return base_sl
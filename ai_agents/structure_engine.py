class StructureEngine:

    def __init__(self):
        pass

    # ==================================================

    def analyze(self, df):
        highs = df["high"]
        lows = df["low"]

        # ==================================================
        # 最近结构
        # ==================================================

        recent_highs = highs.tail(20)
        recent_lows = lows.tail(20)

        # ==================================================
        # Higher High
        # ==================================================

        hh = (
            recent_highs.iloc[-1]
            > recent_highs.iloc[-5]
            > recent_highs.iloc[-10]
        )

        # ==================================================
        # Higher Low
        # ==================================================

        hl = (
            recent_lows.iloc[-1]
            > recent_lows.iloc[-5]
            > recent_lows.iloc[-10]
        )

        # ==================================================
        # Lower High
        # ==================================================

        lh = (
            recent_highs.iloc[-1]
            < recent_highs.iloc[-5]
            < recent_highs.iloc[-10]
        )

        # ==================================================
        # Lower Low
        # ==================================================

        ll = (
            recent_lows.iloc[-1]
            < recent_lows.iloc[-5]
            < recent_lows.iloc[-10]
        )

        # ==================================================
        # 多头结构
        # ==================================================

        if hh and hl:
            return {
                "structure": "BULL"
            }

        # ==================================================
        # 空头结构
        # ==================================================

        if lh and ll:
            return {
                "structure": "BEAR"
            }

        # ==================================================

        return {
            "structure": "RANGE"
        }
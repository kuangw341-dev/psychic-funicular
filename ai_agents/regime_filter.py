import pandas as pd


# ==================================================
class RegimeFilter:
    def __init__(self):
        pass

    # ==================================================
    def ema(
        self,
        series,
        period
    ):
        return series.ewm(
            span=period,
            adjust=False
        ).mean()

    # ==================================================
    def analyze(
        self,
        df_4h,
        df_1d
    ):
        # ==================================================
        # 4H趋势
        # ==================================================
        ema50_4h = self.ema(
            df_4h["close"],
            50
        )
        ema200_4h = self.ema(
            df_4h["close"],
            200
        )

        # ==================================================
        # 1D趋势
        # ==================================================
        ema50_1d = self.ema(
            df_1d["close"],
            50
        )
        ema200_1d = self.ema(
            df_1d["close"],
            200
        )

        # ==================================================
        # Bull
        # ==================================================
        if (
            ema50_4h.iloc[-1]
            > ema200_4h.iloc[-1]
            and
            ema50_1d.iloc[-1]
            > ema200_1d.iloc[-1]
        ):
            return "BULL"

        # ==================================================
        # Bear
        # ==================================================
        elif (
            ema50_4h.iloc[-1]
            < ema200_4h.iloc[-1]
            and
            ema50_1d.iloc[-1]
            < ema200_1d.iloc[-1]
        ):
            return "BEAR"

        # ==================================================
        # Sideways
        # ==================================================
        return "SIDEWAYS"